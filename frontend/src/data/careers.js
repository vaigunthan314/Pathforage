function stackHint(project) {
  const t = (project.techStack || '').toLowerCase()
  if (t.includes('aws') || t.includes('s3') || t.includes('cloudfront') || t.includes('cloud')) return 'cloud'
  if (t.includes('docker') || t.includes('kubernetes') || t.includes('k8s')) return 'container'
  if (t.includes('spring') || t.includes('java')) return 'java'
  if (t.includes('react') || t.includes('html') || t.includes('css') || t.includes('javascript') || t.includes('typescript')) return 'web'
  if (t.includes('python') || t.includes('pandas') || t.includes('scikit')) return 'python'
  if (t.includes('node') || t.includes('express') || t.includes('mongo')) return 'node'
  if (t.includes('sql') || t.includes('mysql') || t.includes('postgres')) return 'data'
  return 'general'
}

