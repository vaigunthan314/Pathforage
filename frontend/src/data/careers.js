function buildHowToBuild(project, testing, deployment) {
  const features = Array.isArray(project.features) && project.features.length
    ? project.features
    : ['the core functionality described in the project brief']
  return HOW_TO_BUILD_PHASES.map(({ phase, title, key }) => ({
    phase,
    title,
    action: (() => {
      switch (key) {
        case 'requirements':
          return `Write down what you are building: ${project.description || 'the project brief'}. Turn the planned capabilities into a checklist you can tick off as you implement them — start with: ${features.slice(0, 3).map(f => f.toLowerCase()).join('; ')}.`
        case 'architecturePlan':
          return `Sketch the structure before coding: ${project.architecture || 'a simple client-service-data layout'}. Keep the layers separate (UI / logic / data access) so each piece can be tested and swapped independently.`
        case 'dataDesign':
          return `Define the data model and interface contract for the ${project.techStack || 'chosen'} stack. Name the entities and fields you need, then design the API endpoints (paths, methods, request/response shapes) before implementing them.`
        case 'implementation':
          return `Implement in small verified increments, one milestone at a time: ${project.milestones && project.milestones.length ? project.milestones.map(m => m.toLowerCase()).join('; ') : 'build, run, verify, then move on'}. Commit after each working increment.`
        case 'testingPhase':
          return testing
        case 'deploymentPhase':
          return deployment
        case 'securityPhase':
          return 'Harden before presenting: keep secrets in environment variables (never commit them), validate all inputs, use secure headers/HTTPS, and add basic monitoring (health endpoint, error logging, and — for cloud/container stacks — resource alerts). Check git history for leaked credentials.'
        default:
          return ''
      }
    })(),
  }))
}

function buildImplementationSteps(project) {
  if (Array.isArray(project.implementationSteps) && project.implementationSteps.length) {
    return project.implementationSteps
  }
  const milestones = Array.isArray(project.milestones) ? project.milestones : []
  const steps = []
  milestones.forEach((m, idx) => {
    if (idx === 0 && !/^(set up|create|build|install|init)/i.test(m)) {
      steps.push(`Set up the project scaffold for the ${project.techStack || 'chosen'} stack and initialize version control.`)
    }
    steps.push(m)
  })
  if (steps.length) {
    steps.push('Run the full application end to end, fix edge cases, and write the README with setup and run instructions.')
  }
  return steps
}

function buildCommonMistakes(project, testing) {
  if (Array.isArray(project.commonMistakes) && project.commonMistakes.length) return project.commonMistakes
  const list = [
    'Skipping input validation and letting empty or malformed data break the flow',
    'Hardcoding credentials or configuration instead of using environment variables',
    'Implementing the happy path only — ignoring error cases, empty states, and failure handling',
    'Deferring testing to the end, then shipping with untested edge cases',
  ]
  const features = Array.isArray(project.features) && project.features.length
    ? project.features.slice(0, 2).map(f => f.toLowerCase())
    : []
  if (features.length) list.unshift(`Half-implementing the planned features (e.g. ${features.join(' and ')}) instead of finishing each one completely`)
  if (project.techStack) list.push(`Ignoring the specifics of ${project.techStack} (version quirks, deployment differences, ecosystem conventions) during implementation`)
  return list.slice(0, 5)
}

function buildExtensionIdeas(project) {
  if (Array.isArray(project.extensionIdeas) && project.extensionIdeas.length) return project.extensionIdeas
  const ideas = []
  const features = Array.isArray(project.features) && project.features.length
    ? project.features.map(f => f.replace(/^[A-Z]/, c => c.toLowerCase()))
    : []
  if (features.length >= 2) {
    ideas.push(`Add a complementary capability: ${features[0].replace(/\.$/, '')} plus ${features[1].replace(/\.$/, '')} in a single cohesive flow`)
  }
  ideas.push('Add persistence options: export/import of data, history tracking, or a saved-state view')
  const stack = stackHint(project)
  if (stack === 'cloud' || stack === 'container') ideas.push('Add monitoring: metrics, health checks, and alerting for the deployed environment')
  if (stack === 'java' || stack === 'node') ideas.push('Add authentication and role-based access control to protect the data')
  if (stack === 'web') ideas.push('Add light polish: loading states, empty states, keyboard navigation, and error toasts')
  if (stack === 'python' || stack === 'data') ideas.push('Add automated reporting: scheduled runs that summarize results into a clear output')
  return ideas.slice(0, 4)
}

function buildInterviewQuestions(project) {
  if (Array.isArray(project.interviewQuestions) && project.interviewQuestions.length) return project.interviewQuestions
  const skills = Array.isArray(project.skills) && project.skills.length ? project.skills.slice(0, 3) : []
  const questions = []
  skills.forEach(skill => {
    questions.push({
      q: `How did you apply ${skill} in this project, and what was the hardest decision you made around it?`,
      a: `Walk through the concrete way ${skill} shaped this project: the choices, the trade-offs you noticed, and what you would do differently next time.`,
    })
  })
  questions.push(
    { q: 'What would you change if the data or requirements grew 10x?', a: 'Discuss scaling the architecture honestly: where it breaks first and what you would refactor.' },
    { q: 'How did you test this project, and what would you add with more time?', a: 'Describe the manual and automated checks you ran, plus the test coverage you would add next.' },
  )
  return questions
}

function buildPortfolioValue(project) {
  if (project.portfolioValue) return project.portfolioValue
  const base = `${(project.description || 'A practical project that exercises real engineering skills.').replace(/\.$/, '.')} This project is directly relevant to ${project.careerPath || 'the target career'} roles.`
  return `${base} Write a README with a short architecture diagram, live demo link (if possible), and screenshots, then list it as a case study.`
}

function buildPrerequisites(project) {
  const skills = Array.isArray(project.skills) && project.skills.length ? project.skills : []
  const skillText = skills.length
    ? `The core skills exercised here are: ${skills.join(', ')}.`
    : 'No specific prerequisite skills are required — everything needed is explained step by step.'
  const difficultyHint =
    project.difficulty === 'Beginner'
      ? 'Designed for beginners: basic concepts are assumed, with every stage broken into small verifiable steps.'
      : project.difficulty === 'Advanced'
        ? 'Aim for this once the related roadmap topics are complete — it assumes solid hands-on experience.'
        : 'Comfort with the fundamentals of the stack is recommended before starting. Completing the related roadmap topics first makes this much smoother.'
  return `${skillText} ${difficultyHint}`
}

function buildWhoShouldBuild(project) {
  const skills = Array.isArray(project.skills) && project.skills.length ? project.skills : []
  const skillText = skills.length ? `, especially if you are practicing ${skills.slice(0, 2).join(' and ')}` : ''
  return `Anyone preparing for a ${project.careerPath || 'technical'} role${skillText}. Start here${project.difficulty === 'Beginner' ? '' : ' once the basics feel comfortable'} and use it as a building block for your portfolio.`
}

function buildMilestoneList(project) {
  return Array.isArray(project.milestones) && project.milestones.length ? project.milestones : ['Set up the project', 'Build the core feature', 'Test the full flow', 'Deploy and document']
}

function buildReadmeChecklist() {
  return [
    'One-line project description and its purpose',
    'Setup instructions: prerequisites, install, and run commands',
    'Architecture overview (short diagram or written summary)',
    'Environment variables and configuration reference (no real secrets)',
    'Testing instructions and what is covered',
    'Deployment steps used to get it live',
    'Screenshots or short demo clip landing near the top',
    'Known limitations and future ideas',
  ]
}

export function getAllProjects() {
  const projects = []
  for (const [careerPath, career] of Object.entries(CAREERS)) {
    for (const p of career.projects) {
      const testing = p.testing || TESTING_GUIDE[stackHint(p)]
      const deployment = p.deployment || DEPLOYMENT_GUIDE[stackHint(p)]
      const expectedOutcome = p.expectedOutcome || p.expectedResult ||
        `A working ${p.name.toLowerCase()} built with ${p.techStack || 'the chosen stack'}: the planned features functional, tested, and documented with run instructions.`
      projects.push({
        id: `${careerPath.toLowerCase().replace(/[^a-z0-9]+/g, '-')}-${p.name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`,
        careerPath,
        career: careerPath,
        title: p.name,
        description: p.description || 'No description available.',
        difficulty: p.difficulty || 'Beginner',
        duration: p.duration || '4-6 hrs',
        skills: Array.isArray(p.skills) ? p.skills : [],
        techStack: (p.techStack || '').split(/[,\/]/).map(s => s.trim()).filter(Boolean),
        architecture: p.architecture || p.description || 'Standard layered architecture.',
        features: Array.isArray(p.features) ? p.features : [],
        milestones: buildMilestoneList(p),
        whyBuild: p.whyBuild || p.whyUseful || 'Builds practical skills.',
        whyUseful: p.whyUseful || p.whyBuild || 'Builds practical skills.',
        problemStatement: p.problemStatement || `${(p.description || `Build a ${p.name.toLowerCase()}`)} Make it functional first, then progressively polish it: validation, errors, tests, and deployment.`,
        whoShouldBuild: p.whoShouldBuild || buildWhoShouldBuild(p),
        prerequisites: p.prerequisites || buildPrerequisites(p),
        implementationSteps: buildImplementationSteps(p),
        howToBuild: p.howToBuild || buildHowToBuild(p, testing, deployment),
        expectedOutcome,
        expectedResult: p.expectedResult || expectedOutcome,
        testing,
        deployment,
        commonMistakes: buildCommonMistakes(p, testing),
        extensionIdeas: buildExtensionIdeas(p),
        readmeChecklist: buildReadmeChecklist(),
        portfolioValue: buildPortfolioValue(p),
        interviewQuestions: buildInterviewQuestions(p),
      })
    }
  }
  return projects
}
